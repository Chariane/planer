export type SupportedLanguage = 'fr' | 'en' | 'es' | 'pt' | 'de';

export interface LanguageOption {
  code: SupportedLanguage;
  label: string;
  nativeLabel: string;
  shortLabel: string;
  locale: string;
}

export const DEFAULT_LANGUAGE: SupportedLanguage = 'fr';
export const LANGUAGE_STORAGE_KEY = 'kplanner-language';

export const SUPPORTED_LANGUAGES: LanguageOption[] = [
  { code: 'fr', label: 'French', nativeLabel: 'Français', shortLabel: 'FR', locale: 'fr-FR' },
  { code: 'en', label: 'English', nativeLabel: 'English', shortLabel: 'EN', locale: 'en-US' },
  { code: 'es', label: 'Spanish', nativeLabel: 'Español', shortLabel: 'ES', locale: 'es-ES' },
  { code: 'pt', label: 'Portuguese', nativeLabel: 'Português', shortLabel: 'PT', locale: 'pt-PT' },
  { code: 'de', label: 'German', nativeLabel: 'Deutsch', shortLabel: 'DE', locale: 'de-DE' },
];

export const isSupportedLanguage = (value: string | null | undefined): value is SupportedLanguage =>
  SUPPORTED_LANGUAGES.some(language => language.code === value);

export const detectBrowserLanguage = (): SupportedLanguage => {
  if (typeof window === 'undefined') return DEFAULT_LANGUAGE;

  const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
  if (isSupportedLanguage(stored)) return stored;

  const browserLanguage = navigator.language.split('-')[0];
  return isSupportedLanguage(browserLanguage) ? browserLanguage : DEFAULT_LANGUAGE;
};


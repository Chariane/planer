export const UI_TRANSLATIONS: Record<SupportedLanguage, Record<string, string>> = {
  fr: {},
  en,
  es,
  pt,
  de,
};

const normalizeUiText = (text: string) => text.replace(/\s+/g, ' ').trim();

const SORTED_TRANSLATION_ENTRIES: Record<SupportedLanguage, Array<[string, string]>> = {
  fr: [],
  en: Object.entries(en).sort((a, b) => b[0].length - a[0].length),
  es: Object.entries(es).sort((a, b) => b[0].length - a[0].length),
  pt: Object.entries(pt).sort((a, b) => b[0].length - a[0].length),
  de: Object.entries(de).sort((a, b) => b[0].length - a[0].length),
};

const TRANSLATION_SOURCE_LOOKUP = Object.values(UI_TRANSLATIONS).reduce<Record<string, string>>((lookup, dictionary) => {
  Object.entries(dictionary).forEach(([source, translated]) => {
    lookup[normalizeUiText(source)] = source;
    lookup[normalizeUiText(translated)] = source;
    lookup[normalizeUiText(source).toLowerCase()] = source;
    lookup[normalizeUiText(translated).toLowerCase()] = source;
  });
  return lookup;
}, {});

export const resolveUiSourceText = (text: string): string => {
  const leading = text.match(/^\s*/)?.[0] ?? '';
  const trailing = text.match(/\s*$/)?.[0] ?? '';
  const normalized = normalizeUiText(text);
  const source = TRANSLATION_SOURCE_LOOKUP[normalized] || TRANSLATION_SOURCE_LOOKUP[normalized.toLowerCase()] || normalized;
  return `${leading}${source}${trailing}`;
};

const getDictionaryTranslation = (dictionary: Record<string, string>, source: string): string | undefined => {
  const exact = dictionary[source];
  if (exact) return exact;

  const lowerSource = source.toLowerCase();
  const found = Object.entries(dictionary).find(([key]) => key.toLowerCase() === lowerSource);
  return found?.[1];
};

export const translateUiText = (text: string, language: SupportedLanguage): string => {
  const sourceText = resolveUiSourceText(text);
  if (language === DEFAULT_LANGUAGE) return sourceText;
  const leading = text.match(/^\s*/)?.[0] ?? '';
  const trailing = text.match(/\s*$/)?.[0] ?? '';
  const normalized = normalizeUiText(sourceText);
  if (!normalized) return text;
  const translated = getDictionaryTranslation(UI_TRANSLATIONS[language], normalized);
  if (translated) return `${leading}${translated}${trailing}`;

  const segmentTranslated = SORTED_TRANSLATION_ENTRIES[language].reduce((value, [source, target]) => {
    if (!source || source.length < 4) return value;
    return value.replace(new RegExp(source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi'), target);
  }, normalized);

  return segmentTranslated !== normalized ? `${leading}${segmentTranslated}${trailing}` : text;
};

export const hasLocalUiTranslation = (text: string, language: SupportedLanguage): boolean => {
  if (language === DEFAULT_LANGUAGE) return true;
  const sourceText = resolveUiSourceText(text);
  const normalized = normalizeUiText(sourceText);
  if (!normalized) return true;
  if (getDictionaryTranslation(UI_TRANSLATIONS[language], normalized)) return true;

  const segmentTranslated = SORTED_TRANSLATION_ENTRIES[language].reduce((value, [source, target]) => {
    if (!source || source.length < 4) return value;
    return value.replace(new RegExp(source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi'), target);
  }, normalized);

  return segmentTranslated !== normalized;
};

export const getLanguageOption = (language: SupportedLanguage): LanguageOption =>
  SUPPORTED_LANGUAGES.find(option => option.code === language) || SUPPORTED_LANGUAGES[0];
